"""共享 Agent 输入边界常量。"""

# 单次生图允许附带的参考图片数量。
MAX_REFERENCE_IMAGE_COUNT = 3
# 每张参考图片的最大字节数，按 5 MiB 计算。
MAX_REFERENCE_IMAGE_BYTES = 5 * 1024 * 1024
# 进入 TokenHub 请求前允许的参考图片总字节数。
MAX_REFERENCE_IMAGE_TOTAL_BYTES = MAX_REFERENCE_IMAGE_COUNT * MAX_REFERENCE_IMAGE_BYTES

